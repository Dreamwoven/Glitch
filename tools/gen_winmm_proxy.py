#!/usr/bin/env python3
"""Generate 100% export-compatible winmm.dll proxy tables from System32\\winmm.dll.

Outputs into Loader/src/proxy/:
  - winmm_exports.def  : linker module definition preserving all names & ordinals
  - winmm_thunks.asm   : x64 MASM jump stubs forwarding directly to real winmm procs
  - winmm_names.inc    : C++ descriptor array used at runtime to resolve each slot
"""

from __future__ import annotations
import os
import sys
import pefile

SYSTEM_WINMM = r"C:\Windows\System32\winmm.dll"
OUT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "src", "proxy"))


def main() -> None:
    if not os.path.exists(SYSTEM_WINMM):
        raise SystemExit(f"System winmm.dll not found at {SYSTEM_WINMM}")

    pe = pefile.PE(SYSTEM_WINMM, fast_load=True)
    pe.parse_data_directories(
        directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]]
    )
    symbols = sorted(pe.DIRECTORY_ENTRY_EXPORT.symbols, key=lambda s: s.ordinal)

    os.makedirs(OUT_DIR, exist_ok=True)

    def_lines = [
        "; AUTO-GENERATED by Loader/tools/gen_winmm_proxy.py - do not edit by hand",
        "LIBRARY winmm",
        "EXPORTS",
    ]
    asm_lines = [
        "; AUTO-GENERATED by Loader/tools/gen_winmm_proxy.py - do not edit by hand",
        "OPTION CASEMAP:NONE",
        "",
        "EXTERN g_winmm_procs:QWORD",
        "EXTERN WinmmEnsureResolved:PROC",
        "",
        ".CODE",
        "",
        "; Helper: lazy-resolve real System32\\winmm.dll if called before DllMain init finishes.",
        "; Expects slot index in r11 (volatile). Preserves all argument registers (rcx,rdx,r8,r9,xmm0-3).",
        "WinmmLazyDispatch PROC",
        "    sub rsp, 98h",
        "    mov [rsp+20h], rcx",
        "    mov [rsp+28h], rdx",
        "    mov [rsp+30h], r8",
        "    mov [rsp+38h], r9",
        "    mov [rsp+40h], r11",
        "    movaps [rsp+50h], xmm0",
        "    movaps [rsp+60h], xmm1",
        "    movaps [rsp+70h], xmm2",
        "    movaps [rsp+80h], xmm3",
        "    call WinmmEnsureResolved",
        "    movaps xmm3, [rsp+80h]",
        "    movaps xmm2, [rsp+70h]",
        "    movaps xmm1, [rsp+60h]",
        "    movaps xmm0, [rsp+50h]",
        "    mov r11, [rsp+40h]",
        "    mov r9,  [rsp+38h]",
        "    mov r8,  [rsp+30h]",
        "    mov rdx, [rsp+28h]",
        "    mov rcx, [rsp+20h]",
        "    add rsp, 98h",
        "    lea rax, g_winmm_procs",
        "    mov rax, [rax + r11*8]",
        "    jmp rax",
        "WinmmLazyDispatch ENDP",
        "",
    ]
    inc_lines = [
        "// AUTO-GENERATED by Loader/tools/gen_winmm_proxy.py - do not edit by hand",
        f"static constexpr size_t kWinmmExportCount = {len(symbols)};",
        "",
        "struct WinmmExportDesc {",
        "    uint16_t ordinal;",
        "    const char* name; // nullptr for NONAME ordinal exports",
        "};",
        "",
        "static constexpr WinmmExportDesc kWinmmExports[] = {",
    ]

    for idx, sym in enumerate(symbols):
        ordinal = sym.ordinal
        name = sym.name.decode("ascii") if sym.name else None
        stub_sym = f"winmm_proxy_stub_{idx}"

        if name:
            def_lines.append(f"    {name}={stub_sym} @{ordinal}")
            inc_lines.append(f'    {{ {ordinal}, "{name}" }},')
        else:
            def_lines.append(f"    winmm_ord_{ordinal}={stub_sym} @{ordinal} NONAME")
            inc_lines.append(f"    {{ {ordinal}, nullptr }},")

        asm_lines.extend([
            f"PUBLIC {stub_sym}",
            f"{stub_sym} PROC",
            f"    mov rax, QWORD PTR [g_winmm_procs + {idx * 8}]",
            "    test rax, rax",
            "    jz @F",
            "    jmp rax",
            "@@:",
            f"    mov r11d, {idx}",
            "    jmp WinmmLazyDispatch",
            f"{stub_sym} ENDP",
        ])

    asm_lines.extend(["", "END", ""])
    inc_lines.extend(["};", ""])

    def_path = os.path.join(OUT_DIR, "winmm_exports.def")
    asm_path = os.path.join(OUT_DIR, "winmm_thunks.asm")
    inc_path = os.path.join(OUT_DIR, "winmm_names.inc")

    with open(def_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(def_lines) + "\n")
    with open(asm_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(asm_lines))
    with open(inc_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(inc_lines))

    print(f"Generated {len(symbols)} winmm proxy exports in {OUT_DIR}")


if __name__ == "__main__":
    main()
